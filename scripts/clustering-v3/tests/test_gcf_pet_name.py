def test_tagged_names_and_offsets():
    from gcf_pet_name import PET_OFFSET, gcf_name, pet_name_for_gcf_name, pet_name_for_id
    assert gcf_name("seed", 42, "v2b2") == "GCF-v2b2-000042"
    assert gcf_name("fragmented", 42, "v2b2") == "GCF-v2b2-F-400042"
    assert gcf_name("seed", 42) == "GCF-000042"
    # the untagged (v3) aliases are unchanged by the offset machinery
    assert pet_name_for_gcf_name("GCF-000042") == pet_name_for_id(42)
    # a tagged name draws from its clustering's offset, so it differs from the v3 alias
    assert pet_name_for_gcf_name("GCF-v2b2-000042") == pet_name_for_id(42, PET_OFFSET["v2b2"])
    assert pet_name_for_gcf_name("GCF-v2b2-000042") != pet_name_for_gcf_name("GCF-000042")
    # the v2 resolution form still parses as untagged; an unknown tag yields no alias
    assert pet_name_for_gcf_name("GCF-04-000042") == pet_name_for_id(42)
    assert pet_name_for_gcf_name("GCF-v9z-000042") is None
    assert pet_name_for_gcf_name("GCF-v7-000042") is None


def test_seed_aliases_never_reuse_a_v3_alias():
    from gcf_pet_name import PET_OFFSET
    # (id + offset) for new seed ids 1..371,084 lands above every v3 id (max 794,186), and
    # stays below the alias space, so the bijection keeps them apart from all v3 aliases.
    assert PET_OFFSET["v2b2"] + 1 > 794_186
    assert PET_OFFSET["v2b2"] + 371_084 < 1198 * 1052


def test_v2b4_seed_aliases_never_reuse_a_v2b2_alias():
    from gcf_pet_name import PET_OFFSET
    n = 1198 * 1052
    # v2b2 holds (id + 794,186) mod n for ids 1..792,568: 794,187..n and 1..326,458.
    v2b2 = {(i + PET_OFFSET["v2b2"]) % n for i in range(1, 792_569)}
    assert all((i + PET_OFFSET["v2b4"]) % n not in v2b2 for i in range(1, 371_120))


def test_v2b5_seed_aliases_never_reuse_a_v2b4_alias():
    from gcf_pet_name import PET_OFFSET
    n = 1198 * 1052
    # v2b4 holds (id + 1,586,754) mod n for its seed ids 1..371,119 and fragmented ids 400,001..792,426.
    v2b4 = {(i + PET_OFFSET["v2b4"]) % n for i in (*range(1, 371_120), *range(400_001, 792_427))}
    # Every possible v2b5 seed id (fragmented ids start at 400,000).
    assert all((i + PET_OFFSET["v2b5"]) % n not in v2b4 for i in range(1, 400_000))


