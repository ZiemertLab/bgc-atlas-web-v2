#!/usr/bin/env python3
"""Generate an FK-safe, append-only Postgres load script for the MAG collections.

MAG collection ids are source-scoped and they carry no studies/biomes/gcfs/taxonomies,
so every row is a disjoint INSERT. Each collection is wrapped in its own transaction:
a re-run of a loaded collection aborts on the data_sources PK conflict.

Writes a .sql script only; run it against bgc_atlas_v2 with:

    PGPASSWORD=... psql -h localhost -U bgc_owner -d bgc_atlas_v2 -f <out.sql>

Afterwards refresh sample_summary, assembly_samples_mv and bgc_biome_summary_mv.

Usage:
    python -m scripts.populator.tools.load_mag_collections \
        [--base /data/bgc-atlas/data-v2/populator-out] \
        [--out  /data/bgc-atlas/data-v2/populator-out/_mag-load.sql] \
        [--collections gem mfd-lr mfd-sr smag spire tpmc omd-v2]
"""
import argparse
from pathlib import Path

from scripts.populator.schema import TABLES, load_order

# The 9 tables a MAG collection emits (intersection with load_order below keeps order).
MAG_TABLES = {
    "data_sources", "samples", "assemblies", "analyses", "antismash_runs",
    "bgcs", "sample_assemblies", "sample_analyses", "assembly_analyses",
}
DEFAULT_COLLECTIONS = ["gem", "mfd-lr", "mfd-sr", "smag", "spire", "tpmc", "omd-v2"]
DEFAULT_BASE = "/data/bgc-atlas/data-v2/populator-out"


def _tsv_files(d: Path, table: str):
    """Single <table>.tsv, else streamed <table>_NNNN.tsv parts (bgcs)."""
    single = d / f"{table}.tsv"
    if single.exists():
        return [single]
    return sorted(d.glob(f"{table}_[0-9]*.tsv"))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base", default=DEFAULT_BASE)
    ap.add_argument("--out", default=None)
    ap.add_argument("--collections", nargs="+", default=DEFAULT_COLLECTIONS)
    args = ap.parse_args(argv)

    base = Path(args.base)
    out = Path(args.out) if args.out else base / "_mag-load.sql"
    order = [t for t in load_order() if t in MAG_TABLES]

    lines = [
        "-- MAG collections incremental load (append-only, FK-safe).",
        "-- Generated by tools/load_mag_collections.py. Target: bgc_atlas_v2 ONLY.",
        f"-- collections: {', '.join(args.collections)}",
        "",
    ]
    ncopy = 0
    per_coll = {}
    missing = []
    for coll in args.collections:
        cdir = base / coll
        if not cdir.is_dir():
            missing.append(coll)
            continue
        block = [f"-- ===== {coll} =====", "BEGIN;"]
        n = 0
        for t in order:
            cols = ", ".join(TABLES[t].columns)
            for f in _tsv_files(cdir, t):
                block.append(
                    rf"\copy {t} ({cols}) FROM '{f}' WITH (FORMAT text, NULL '\N');")
                n += 1
                ncopy += 1
        block.append("COMMIT;")
        block.append("")
        lines.extend(block)
        per_coll[coll] = n

    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")
    print(f"total \\copy statements: {ncopy}")
    for coll in args.collections:
        if coll in per_coll:
            print(f"  {coll:10s} {per_coll[coll]} \\copy stmts")
    if missing:
        print(f"WARNING: collection dirs not found (skipped): {', '.join(missing)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
