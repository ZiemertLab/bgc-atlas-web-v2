/**
 * Generates src/lib/utils/gold-leaf-branches.generated.ts: GOLD level-2..5 leaf
 * name -> the branch it sits under (top-level ecosystem, or "plants" /
 * "aquatic" for the Host-associated:Plants and Environmental:Aquatic subtrees).
 *
 * Needed because the GCF browse index stores each level's distribution keyed by
 * the bare leaf ("Roots"), not the path, so a chart cell cannot otherwise tell
 * which branch a segment belongs to. A leaf found under several branches takes
 * the one holding >= 95% of the samples that carry it ("Soil": 99.3%
 * Environmental); one split more evenly ("Wetlands", "Wood") is left out and
 * renders as unknown.
 *
 * Run when the GOLD vocabulary in samples changes:
 *   node scripts/generate-gold-leaf-branches.mjs
 */

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const SQL = `
with s as (
  select lower(trim(split_part(gold_ecosystem_path, ':', n))) leaf,
         case when lower(trim(split_part(gold_ecosystem_path, ':', 1))) = 'host-associated'
                   and lower(trim(split_part(gold_ecosystem_path, ':', 2))) = 'plants' then 'plants'
              when lower(trim(split_part(gold_ecosystem_path, ':', 1))) = 'environmental'
                   and lower(trim(split_part(gold_ecosystem_path, ':', 2))) = 'aquatic' then 'aquatic'
              else lower(trim(split_part(gold_ecosystem_path, ':', 1))) end branch
  from samples, generate_series(2, 5) n
  where gold_ecosystem_path is not null and trim(split_part(gold_ecosystem_path, ':', n)) <> ''
), c as (
  select leaf, branch, count(*) k, sum(count(*)) over (partition by leaf) total
  from s group by leaf, branch
)
select leaf, branch from c
where branch in ('environmental', 'host-associated', 'engineered', 'mixed', 'plants', 'aquatic')
  and k >= 0.95 * total
order by leaf`;

const out = execFileSync('psql', ['-q', '-d', 'bgc_atlas_v2', '-AtF', '\t', '-c', 'set statement_timeout = 0', '-c', SQL], { encoding: 'utf8' });
const rows = out.trim().split('\n').filter(Boolean).map((line) => line.split('\t')).filter((r) => r.length === 2);
if (rows.length < 100) throw new Error(`only ${rows.length} leaves; refusing to overwrite`);

const body = rows.map(([leaf, branch]) => `  ${JSON.stringify(leaf)}: '${branch}',`).join('\n');
const file = `// Generated by scripts/generate-gold-leaf-branches.mjs — do not edit by hand.
// GOLD level-2..5 leaf (lowercased) -> branch. A leaf under several branches takes one holding >= 95% of its samples, else is omitted.

export type GoldBranch = 'environmental' | 'host-associated' | 'engineered' | 'mixed' | 'plants' | 'aquatic';

export const GOLD_LEAF_BRANCH: Record<string, GoldBranch> = {
${body}
};
`;
writeFileSync(fileURLToPath(new URL('../src/lib/utils/gold-leaf-branches.generated.ts', import.meta.url)), file);
console.log(`wrote ${rows.length} leaves`);
